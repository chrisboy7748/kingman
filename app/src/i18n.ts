const dict: Record<Lang, Record<Key, string>> = { en, ar };

export function translate(lang: Lang, key: Key, vars?: Record<string, string>) {
  let s = dict[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

export function useT() {
  const lang = useAppState((s) => s.lang);
  const t = (key: Key, vars?: Record<string, string>) => translate(lang, key, vars);
  return { t, lang, L: <T,>(o: { en: T; ar: T }) => o[lang] };
}
